const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const loaded = new Map();

function load(file) {
  const absolute = path.resolve(file);
  if (loaded.has(absolute)) return loaded.get(absolute);
  const mod = { exports: {} };
  loaded.set(absolute, mod.exports);
  const code = ts.transpile(fs.readFileSync(absolute, 'utf8'), { target: ts.ScriptTarget.ES2021, module: ts.ModuleKind.CommonJS });
  new Function('module', 'exports', 'require', code)(mod, mod.exports, specifier => specifier.startsWith('.') ? load(path.resolve(path.dirname(absolute), `${specifier}.ts`)) : require(specifier));
  return mod.exports;
}
